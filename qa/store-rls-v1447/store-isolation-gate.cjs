const TABLES=Object.freeze(['products','customers','orders','order_items','conversations','messages']);
const WRITER_ROLES=Object.freeze(['owner','manager']);
const BLOCKERS=Object.freeze({
  FULL_RESTORE:'B01_FULL_RESTORE_AND_ROLLBACK_UNVERIFIED',
  OWNER_PROOF:'B02_FOUR_ROW_OWNER_STORE_PROOF_MISSING',
  SCHEMA:'B03_CANONICAL_STORE_MEMBERSHIP_SCHEMA_MISSING',
  STORE_IDS:'B04_CORE_STORE_IDS_MISSING',
  LEGACY_POLICIES:'B05_TENANT_WIDE_PERMISSIVE_READ_POLICY_PRESENT',
  STORE_POLICIES:'B06_STORE_SCOPED_READ_POLICIES_UNVERIFIED',
  PRODUCT_V2:'B07_STORE_AWARE_PRODUCT_V2_UNVERIFIED',
  LEGACY_WRITER:'B08_LEGACY_WRITER_COMPATIBILITY_UNVERIFIED',
  JWT:'B09_REAL_SIGNED_JWT_ACCEPTANCE_MISSING',
  APPROVAL:'B10_SEPARATE_HOSTED_CHANGE_APPROVAL_MISSING'
});
function isObject(x){return x!==null&&typeof x==='object'&&!Array.isArray(x);}
function canReadSynthetic({identity,row,memberships}={}){
  // identity is generated by SYNTHETIC server fixture ONLY, not a client-provided JWT.
  if(!isObject(identity)||identity.verifiedBy!=='SYNTHETIC_AUTH_SERVER'||
     identity.active!==true||typeof identity.userId!=='string'||
     !isObject(row)||typeof row.tenantId!=='string'||typeof row.storeId!=='string'||
     !Array.isArray(memberships)) return false;
  return memberships.some(m=>isObject(m)&&m.source==='SYNTHETIC_STORE_REGISTRY'&&
    m.userId===identity.userId&&m.tenantId===row.tenantId&&m.storeId===row.storeId&&
    m.active===true&&m.storeActive===true&&m.tenantActive===true&&
    m.subscriptionActive===true&&WRITER_ROLES.includes(m.role));
}
function assessReleasePreflight(snapshot){
  const s=isObject(snapshot)?snapshot:{};
  const reasons=[];
  if(s.fullArchiveRestoreAndRollbackVerified!==true) reasons.push(BLOCKERS.FULL_RESTORE);
  if(s.fourRowsIndividuallyAttestedAndReviewed!==true) reasons.push(BLOCKERS.OWNER_PROOF);
  if(s.storesExist!==true||s.storeMembershipsExist!==true) reasons.push(BLOCKERS.SCHEMA);
  if(!Array.isArray(s.coreTables)||s.coreTables.length!==TABLES.length||
     !TABLES.every(name=>s.coreTables.some(t=>t?.name===name&&t.storeId===true&&t.rls===true&&t.forceRls===true)))
      reasons.push(BLOCKERS.STORE_IDS);
  if(!Array.isArray(s.coreTables)||s.coreTables.length!==TABLES.length||
     s.coreTables.some(t=>!t||t.permissiveTenantReadPolicies!==0))
      reasons.push(BLOCKERS.LEGACY_POLICIES);
  if(!Array.isArray(s.coreTables)||s.coreTables.length!==TABLES.length||
     !TABLES.every(name=>s.coreTables.some(t=>t?.name===name&&t.storeScopedReadPolicyReviewed===true)))
      reasons.push(BLOCKERS.STORE_POLICIES);
  if(s.storeAwareProductV2Reviewed!==true) reasons.push(BLOCKERS.PRODUCT_V2);
  if(s.legacyWriterCallersReviewed!==true) reasons.push(BLOCKERS.LEGACY_WRITER);
  if(s.realDistinctSignedJwtAcceptance!==true) reasons.push(BLOCKERS.JWT);
  if(s.separateMigrationApproval!==true) reasons.push(BLOCKERS.APPROVAL);
  return Object.freeze({
    status:reasons.length?'BLOCKED':'READY_FOR_INDEPENDENT_REVIEW_ONLY',
    blockers:Object.freeze(reasons),
    // Deliberately always false: this module cannot authorize hosted changes.
    canRunHostedMigration:false,
    canWriteHostedData:false,
    canCallProvider:false,
    testsAreSyntheticOnly:true
  });
}
module.exports=Object.freeze({TABLES,BLOCKERS,canReadSynthetic,assessReleasePreflight});
