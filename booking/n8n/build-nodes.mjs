// Prints the jsCode for the 3 n8n Code nodes of the booking flow, generated from booking/lib/*.mjs
// so the nodes and the tests can never drift. Never edit these nodes by hand inside n8n.
//   node booking/n8n/build-nodes.mjs validate   -> "Validate Booking"  (inputs: Booking Input, Read Services, Read Bookings, Shop Settings)
//   node booking/n8n/build-nodes.mjs payment    -> "Match Payment"     (inputs: Bank Webhook, Read Services, Read Bookings, Shop Settings)
//   node booking/n8n/build-nodes.mjs reminders  -> "Due Reminders"     (inputs: Read Bookings, Shop Settings)
import { readFileSync } from 'node:fs';

const LIBS = ['vn.mjs', 'deposit.mjs', 'booking-rules.mjs', 'messages.mjs'];
function inlineLibs() {
  return LIBS.map((f) => readFileSync(new URL('../lib/' + f, import.meta.url), 'utf8')
    .replace(/^import .*$/gm, '')
    .replace(/^export /gm, '')).join('\n');
}

// "Shop Settings" is a Set node holding the shop's own (non-secret) choices: hours, capacity, bank BIN/account.
const SETTINGS = "const shop = $('Shop Settings').first().json; const settings = { ...DEFAULT_SETTINGS, ...(shop.booking || {}) };";

const GLUE = {
  validate: [
    SETTINGS,
    "const services = $('Read Services').all().map(i => i.json);",
    "const bookings = $('Read Bookings').all().map(i => i.json);",
    "const row = validateBooking({ input: $('Booking Input').first().json, services, bookings, nowMs: Date.now(), rand: Math.random, settings });",
    "if (!row.ok) return [{ json: row }];",
    "let qrUrl = '';",
    "if (row.coc_vnd > 0) qrUrl = vietQrUrl({ bank: shop.bank_bin, account: shop.bank_account, accountName: shop.bank_name, amount: row.coc_vnd, code: row.ma_chuyen_khoan });",
    "return [{ json: { ...row, qr_url: qrUrl, reply: bookingCreatedText(row, { qrUrl, holdMin: settings.depositHoldMin }), owner_text: ownerText('new', row) } }];",
  ],
  payment: [
    SETTINGS,
    "const services = $('Read Services').all().map(i => i.json);",
    "const bookings = $('Read Bookings').all().map(i => i.json);",
    "const nowMs = Date.now();",
    "const transfer = readTransfer($('Bank Webhook').first().json.body);",
    "const r = matchTransfer({ transfer, bookings, shopAccount: shop.bank_account, nowMs, slotStillFree: (b) => slotStillFree(b, services, bookings, nowMs, settings) });",
    "const row = bookings.find(b => b.request_id === r.request_id) || {};",
    "const ownerKind = r.action === 'mark_paid' ? 'paid' : r.action;",
    "const notifyOwner = ['mark_paid', 'underpaid', 'late_slot_taken', 'unmatched'].includes(r.action);",
    "return [{ json: { ...r, transfer_id: transfer ? transfer.id : '', notify_owner: notifyOwner, owner_text: notifyOwner ? ownerText(ownerKind, row, { ...r, amount: r.amount ?? (transfer ? transfer.amount : 0) }) : '', customer_text: r.action === 'mark_paid' ? depositReceivedText(row) : '' } }];",
  ],
  reminders: [
    SETTINGS,
    "const bookings = $('Read Bookings').all().map(i => i.json);",
    "const sentKeys = new Set(bookings.flatMap(b => String(b.da_nhac || '').split(',').filter(Boolean).map(k => b.request_id + ':' + k)));",
    "return dueReminders({ bookings, nowMs: Date.now(), sentKeys, shopName: shop.shop_name || 'Shop' }).map(json => ({ json }));",
  ],
};

export function buildNode(name) {
  if (!GLUE[name]) throw new Error('unknown node ' + name);
  return ['// GENERATED by booking/n8n/build-nodes.mjs (' + name + '). Do not edit in n8n.', inlineLibs(), ...GLUE[name], ''].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(buildNode(process.argv[2]));
