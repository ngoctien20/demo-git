#!/usr/bin/env node
// Copies the shared web card renderer + card style into assets/shop-demo/ so the public Demo page
// runs the exact same code as config-core. `--check` fails if the copies drifted (used by tests/CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SHOP_DEMO_COPIES = [
  ['config-core/web/widget-blocks.js', 'assets/shop-demo/widget-blocks.js'],
  ['config-core/web/widget-theme.css', 'assets/shop-demo/widget-theme.css'],
  ['config-core/lib/card-style.mjs', 'assets/shop-demo/card-style.mjs'],
];
// The Demo page loads one classic script (works from file:// in visual QA and old browsers):
// each module is wrapped in its own scope, imports become lookups, exports are collected.
const BUNDLE_ORDER = [
  ['card-style', 'config-core/lib/card-style.mjs'],
  ['widget-blocks', 'config-core/web/widget-blocks.js'],
  ['shop-bot', 'assets/shop-demo/shop-bot.mjs'],
  ['shop-demo', 'assets/shop-demo/shop-demo.js'],
];
export function bundle() {
  const parts = ['// GENERATED by scripts/sync-shop-demo.mjs — do not edit. Sources: ' + BUNDLE_ORDER.map(([, f]) => f).join(', '),
    '(function () {', "'use strict';", 'const __m = {};'];
  for (const [name, file] of BUNDLE_ORDER) {
    let src = readFileSync(join(root, file), 'utf8');
    src = src.replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/([\w-]+)\.m?js';\s*$/gm, (_, names, mod) => {
      if (!BUNDLE_ORDER.some(([n]) => n === mod)) throw new Error(file + ': unknown import ' + mod);
      return 'const {' + names + "} = __m['" + mod + "'];";
    });
    if (/^\s*import\s/m.test(src)) throw new Error(file + ': unsupported import form');
    const names = [...src.matchAll(/^export\s+(?:async\s+)?(?:const|let|function)\s+(\w+)/gm)].map((m) => m[1]);
    src = src.replace(/^export\s+/gm, '');
    parts.push('// ---- ' + file, '(function () {', src.trimEnd(), "__m['" + name + "'] = { " + names.join(', ') + ' };', '})();');
  }
  parts.push('})();', '');
  return parts.join('\n');
}

const check = process.argv.includes('--check');
let drift = 0;
for (const [src, dst] of SHOP_DEMO_COPIES) {
  const want = readFileSync(join(root, src), 'utf8');
  let have = null; try { have = readFileSync(join(root, dst), 'utf8'); } catch {}
  if (have === want) continue;
  if (check) { console.error('out of sync: ' + dst + ' (run node scripts/sync-shop-demo.mjs)'); drift++; }
  else { writeFileSync(join(root, dst), want); console.log('copied ' + dst); }
}
{
  const dst = 'assets/shop-demo/shop-demo.bundle.js';
  const want = bundle();
  let have = null; try { have = readFileSync(join(root, dst), 'utf8'); } catch {}
  if (have !== want) {
    if (check) { console.error('out of sync: ' + dst + ' (run node scripts/sync-shop-demo.mjs)'); drift++; }
    else { writeFileSync(join(root, dst), want); console.log('built ' + dst); }
  }
}
if (drift) process.exit(1);
